class ProvisionSchoolForm(forms.ModelForm):
    admin_full_name = forms.CharField(label="First admin — full name")
    admin_email = forms.EmailField(label="First admin — email")
    admin_password = forms.CharField(
        label="First admin — password", widget=forms.PasswordInput, min_length=8
    )

    class Meta:
        model = Client
        fields = ("name", "slug")  # schema/code are auto-generated by provision_school

    def clean_slug(self):
        return (self.cleaned_data.get("slug") or "").strip() or None


