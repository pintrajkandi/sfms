_STAT_TTL = 300  # cross-tenant stat columns are cached to avoid an N+1 across schemas


def _public() -> str:
    return get_public_schema_name()


def _tenant_stat(client: Client, key: str, fn):
    """Cached per-schema stat (keyed by schema) so the changelist isn't an N+1."""
    if client.schema_name == _public():
        return "—"
    cache_key = f"admin_stat:{client.schema_name}:{key}"
    val = cache.get(cache_key)
    if val is None:
        try:
            with tenant_context(client):
                val = fn()
        except Exception:
            return "?"
        cache.set(cache_key, val, _STAT_TTL)
    return val


