@action(description="Resend verification email to school admin(s)")
def resend_admin_verification(modeladmin, request, queryset):
    from apps.accounts.services import send_verification_email

    total = 0
    for client in queryset.exclude(schema_name=_public()):
        with tenant_context(client):
            for user in User.objects.filter(email_verified=False):
                send_verification_email(user, school_name=client.name, slug=client.slug)
                total += 1
    modeladmin.message_user(request, f"Queued {total} verification email(s).", messages.SUCCESS)


def _require_reauth(modeladmin, request) -> bool:
    """Block a sensitive action unless the operator re-authenticated recently."""
    from apps.core.middleware import reauth_fresh

    if reauth_fresh(request):
        return True
    modeladmin.message_user(
        request,
        "This action needs a fresh login. Log out and back in, then retry.",
        messages.ERROR,
    )
    return False


@action(description="Suspend (block sign-in)")
def suspend_schools(modeladmin, request, queryset):
    if not _require_reauth(modeladmin, request):
        return
    n = queryset.exclude(schema_name=_public()).update(is_active=False)
    modeladmin.message_user(request, f"Suspended {n} school(s).", messages.WARNING)


@action(description="Reactivate")
def reactivate_schools(modeladmin, request, queryset):
    n = queryset.update(is_active=True)
    modeladmin.message_user(request, f"Reactivated {n} school(s).", messages.SUCCESS)


